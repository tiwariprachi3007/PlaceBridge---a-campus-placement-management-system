#ifndef PLACEMENT_OFFICER_H
#define PLACEMENT_OFFICER_H

// Request only the base types to break the DataStore/domain-model include cycle.
#define PLACEBRIDGE_DATA_MANAGER_TYPES_ONLY
#include "DataManager.h"
#undef PLACEBRIDGE_DATA_MANAGER_TYPES_ONLY
#include <QString>
#include <QFile>
#include <QTextStream>
#include <QDateTime>

// ============================================================================
// OOP CONCEPT: INHERITANCE + POLYMORPHISM - PlacementOfficer IS-A User
// ============================================================================
class PlacementOfficer : public User {
private:
    QString employeeId;

public:
    PlacementOfficer(QString name, QString email, QString employeeId)
        : User(std::move(name), std::move(email)), employeeId(std::move(employeeId)) {}

    QString role() const override { return "Placement Officer"; }
    Permissions::Role accountRole() const override { return Permissions::Role::Admin; }

    QString getEmployeeId() const { return employeeId; }
    void setEmployeeId(const QString &id) { employeeId = id; }

    // Plain-text summary used by the Reports page.
    QString summaryText(int students, int placed, int drives, int applications) const {
        QString t;
        QTextStream out(&t);
        out << "==========================================\n";
        out << "        PLACEBRIDGE PLACEMENT REPORT      \n";
        out << "==========================================\n";
        out << "Generated On     : " << QDateTime::currentDateTime().toString("yyyy-MM-dd hh:mm:ss") << "\n";
        out << "Generated By     : " << name << " (" << role() << " - ID: " << employeeId << ")\n";
        out << "Contact Email    : " << email << "\n";
        out << "------------------------------------------\n";
        out << "Total Students   : " << students << "\n";
        out << "Placed Students  : " << placed << "\n";
        out << "Company Drives   : " << drives << "\n";
        out << "Applications     : " << applications << "\n";
        out << "==========================================\n";
        return t;
    }

    bool exportSummaryReport(const QString &outputPath, int students, int placed,
                             int drives, int applications) const {
        QFile file(outputPath);
        if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) return false;
        QTextStream out(&file);
        out << summaryText(students, placed, drives, applications);
        return true;
    }
};

class DepartmentCoordinator final : public User {
    QString branch;
public:
    DepartmentCoordinator(QString name, QString email, QString branchName)
        : User(std::move(name), std::move(email)), branch(std::move(branchName)) {}

    QString role() const override { return "Department Coordinator"; }
    Permissions::Role accountRole() const override { return Permissions::Role::Coordinator; }
    QString getBranch() const { return branch; }
};

#endif // PLACEMENT_OFFICER_H
